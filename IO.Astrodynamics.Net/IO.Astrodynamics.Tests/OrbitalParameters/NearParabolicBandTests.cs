        double a = sv.SemiMajorAxis();
        double n = sv.MeanMotion();

        // Assert: −μ/(2ξ) and √(μ/|a|³), the conic of every e ≠ 1 (before: +Infinity and Barker's √(μ/(2q³)), 2e9 times n
        // at e − 1 = ±5e-7)
