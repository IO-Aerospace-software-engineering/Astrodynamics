"""Write the GMAT R2026a scripts of the comparison of IO.Astrodynamics with GMAT (H2 of phase 2, feature 1; #408).

Reads cases.json (IO.Astrodynamics.Tests/Data/GmatReference/cases.json, written by GmatCasesFileTests from the
reference cases of the library) and writes, for each case, into <output>/<case>/:

  nominal.script      the state and Phi (Sat.OrbitSTM) at every output epoch
  nominal_half.script the same at half the fixed step
  cd_<k><p|m>.script  the state at every output epoch, from the initial state perturbed by +/- the step of the
                      central differences on component k (x, y, z, vx, vy, vz), or on Cd (cd) or Cr (cr)
  density.script      the state and GMAT's atmospheric density at every output epoch (cases with drag)
All the reports are in EarthMJ2000Eq, km and km/s.
  cov.script          the same and P (Sat.OrbitErrorCovariance) at every output epoch, from P0 (cases with a
                      covariance); GMAT takes P0 in MJ2000Eq axes only: the numbers of cases.json are given there,
                      and GmatReferenceTests propagates the same P0 turned to ICRF
  snc_<dt>.script     the same from a small diagonal P0 with GMAT's state noise compensation, q_T alone, at a
                      fixed step of dt seconds: GMAT
                      adds its discrete noise at every integration step (an UpdateTimeStep longer than the step
                      changes nothing, measured), so the step sets the interval of the discrete form

Models, as aligned in the design of #408:
  - the state given in EarthICRF, whose axes are those of SPICE J2000; integration and reports in EarthMJ2000Eq,
    every report turned to ICRF by the constant rotation R0 of the start (decision 1, corrected by the measurement:
    see GmatReport);
  - the GM of the Earth and of every third body set to those of IO.Astrodynamics;
  - the EGM2008 field of IO.Astrodynamics converted to .cof, the kernel GM in its header, the radius of the model and
    the coefficients rescaled to the GM of the model (egm2008_to_cof.py, decision 2, #410);
  - the ephemerides of the same SPK (de440s.bsp) through SPICE; the barycentres of the planets as user-defined bodies
    on their NAIF identifiers (decision 4);
  - SRP: spherical model, the flux at 1 AU and the AU of IO.Astrodynamics, the Earth and Sun radii of its PCK;
  - drag: NRLMSISE-00 with constant F10.7, F10.7A and Kp (ap = 4 for Kp = 1, as Ap = 4 in the library);
  - PrinceDormand78 at the fixed step of the case (decision 7), the output epochs on its grid.

The scripts carry three placeholders, replaced by run_gmat.sh: @SPK@ (the SPK file), @COF@ (the .cof file) and @OUT@
(the directory of the reports).

Usage: python3 -I -B generate_scripts.py <cases.json> <output directory>
"""
import json
import os
import sys

COMPONENTS = ["x", "y", "z", "vx", "vy", "vz"]

# GMAT's built-in bodies for the NAIF identifiers of the cases; any other body is created as a user-defined one
BUILT_IN = {10: "Sun", 301: "Luna"}


def km(value):
    """A length or a velocity of the case in km or km/s, as GMAT reads them."""
    return repr(value / 1000.0)


def gm_km(value):
    return repr(value / 1.0e9)


def epoch_gmat(iso):
    """2021-03-20T12:00:00.000 to GMAT's Gregorian format, 20 Mar 2021 12:00:00.000."""
    months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
    date, time = iso.split("T")
    year, month, day = date.split("-")
    return "%s %s %s %s" % (day, months[int(month) - 1], year, time)


def body_name(body):
    if body["naif_id"] in BUILT_IN:
        return BUILT_IN[body["naif_id"]]
    return "Body%d" % body["naif_id"]


def header(case, state, coefficients):
    lines = [
        "% Generated by tools/gmat_reference/generate_scripts.py from cases.json; do not edit.",
        "%% Case %s (reference case %s of IO.Astrodynamics)." % (case["name"], case["from"]),
        "GMAT SolarSystem.EphemerisSource = 'SPICE';",
        "GMAT SolarSystem.SPKFilename = '@SPK@';",
        "GMAT Earth.Mu = %s;" % gm_km(case["earth"]["gm_m3_s2"]),
        "GMAT Earth.EquatorialRadius = %s;" % km(case["earth"]["equatorial_radius_m"]),
        "GMAT Earth.Flattening = %r;" % case["earth"]["flattening"],
        "GMAT Sun.EquatorialRadius = %s;" % km(case["sun_equatorial_radius_m"]),
    ]
    for body in case["third_bodies"]:
        name = body_name(body)
        if body["naif_id"] not in BUILT_IN:
            lines += [
                "Create Planet %s;" % name,
                "GMAT %s.NAIFId = %d;" % (name, body["naif_id"]),
                "GMAT %s.CentralBody = 'Sun';" % name,
                "GMAT %s.PosVelSource = 'SPICE';" % name,
                "GMAT %s.OrbitSpiceKernelName = {'@SPK@'};" % name,
            ]
        lines.append("GMAT %s.Mu = %s;" % (name, gm_km(body["gm_m3_s2"])))

    spacecraft = case["spacecraft"]
    # The state is given in GMAT's EarthICRF, whose axes are those of SPICE J2000 (measured: the Sun of de440s in
    # EarthICRF equals SPICE to 2e-16), through Probe; GMAT integrates in EarthMJ2000Eq, which it turns from ICRF by a
    # slowly varying rotation (2.1e-7 rad in 2021), and accepts a covariance only on a spacecraft in MJ2000Eq axes, so
    # the mission sequence copies the state of Probe in EarthMJ2000Eq into Sat first (copy_state)
    lines += [
        "Create Spacecraft Probe;",
        "GMAT Probe.DateFormat = TDBGregorian;",
        "GMAT Probe.Epoch = '%s';" % epoch_gmat(case["epoch_tdb"]),
        "GMAT Probe.CoordinateSystem = EarthICRF;",
        "GMAT Probe.DisplayStateType = Cartesian;",
    ]
    for name, value in zip(["X", "Y", "Z", "VX", "VY", "VZ"], state):
        lines.append("GMAT Probe.%s = %s;" % (name, km(value)))
    lines += [
        "Create Spacecraft Sat;",
        "GMAT Sat.DateFormat = TDBGregorian;",
        "GMAT Sat.Epoch = '%s';" % epoch_gmat(case["epoch_tdb"]),
        "GMAT Sat.CoordinateSystem = EarthMJ2000Eq;",
        "GMAT Sat.DisplayStateType = Cartesian;",
    ]
    lines += [
        "GMAT Sat.DryMass = %r;" % spacecraft["mass_kg"],
        "GMAT Sat.DragArea = %r;" % spacecraft["area_m2"],
        "GMAT Sat.SRPArea = %r;" % spacecraft["area_m2"],
        "GMAT Sat.Cd = %r;" % coefficients[0],
        "GMAT Sat.Cr = %r;" % coefficients[1],
        "Create ForceModel FM;",
        "GMAT FM.CentralBody = Earth;",
        "GMAT FM.PrimaryBodies = {Earth};",
        "GMAT FM.GravityField.Earth.Degree = %d;" % case["earth"]["geopotential_degree"],
        "GMAT FM.GravityField.Earth.Order = %d;" % case["earth"]["geopotential_degree"],
        "GMAT FM.GravityField.Earth.PotentialFile = '@COF@';",
        "GMAT FM.GravityField.Earth.TideModel = 'None';",
        "GMAT FM.PointMasses = {%s};" % ", ".join(body_name(b) for b in case["third_bodies"]),
        "GMAT FM.RelativisticCorrection = Off;",
        "GMAT FM.ErrorControl = None;",
    ]
    if case["srp"]:
        lines += [
            "GMAT FM.SRP = On;",
            "GMAT FM.SRP.SRPModel = Spherical;",
            "GMAT FM.SRP.Flux = %r;" % case["srp_flux_at_1_au_w_m2"],
            "GMAT FM.SRP.Nominal_Sun = %s;" % km(case["au_m"]),
        ]
    else:
        lines.append("GMAT FM.SRP = Off;")
    if case["drag"]:
        weather = case["space_weather"]
        lines += [
            "GMAT FM.Drag.AtmosphereModel = NRLMSISE00;",
            "GMAT FM.Drag.HistoricWeatherSource = 'ConstantFluxAndGeoMag';",
            "GMAT FM.Drag.PredictedWeatherSource = 'ConstantFluxAndGeoMag';",
            "GMAT FM.Drag.F107 = %r;" % weather["f107"],
            "GMAT FM.Drag.F107A = %r;" % weather["f107a"],
            "GMAT FM.Drag.MagneticIndex = %r;" % weather["kp"],
        ]
    else:
        lines.append("GMAT FM.Drag.AtmosphereModel = None;")
    lines += [
        "Create Propagator Prop;",
        "GMAT Prop.FM = FM;",
        "GMAT Prop.Type = PrinceDormand78;",
        "GMAT Prop.InitialStepSize = %r;" % case["fixed_step_s"],
        "GMAT Prop.MinStep = 0;",
        "GMAT Prop.MaxStep = %r;" % case["fixed_step_s"],
    ]
    return lines


def report_file(case, variant):
    return [
        "Create ReportFile RF;",
        "GMAT RF.Filename = '@OUT@/%s/%s.txt';" % (case["name"], variant),
        "GMAT RF.Precision = 17;",
        "GMAT RF.WriteHeaders = false;",
        "GMAT RF.LeftJustify = On;",
    ]


def output_spans(case):
    """The durations of the successive Propagate commands, s: the output interval, and what remains at the end."""
    spans, t = [], 0.0
    interval, duration = case["output_interval_s"], case["duration_s"]
    while t + interval < duration:
        spans.append(interval)
        t += interval
    spans.append(duration - t)
    return spans


def sequence(case, options, reports, setup=()):
    """The mission sequence: the state of Probe copied into Sat, the lines of setup (the assignment of P0), the reports
    at the start, then a Propagate and the reports at every output epoch."""
    copy_state = ["Sat.%s = Probe.EarthMJ2000Eq.%s;" % (name, name) for name in ["X", "Y", "Z", "VX", "VY", "VZ"]]
    lines = ["BeginMissionSequence;"] + copy_state + list(setup) + reports
    for span in output_spans(case):
        lines.append("Propagate Prop(Sat%s) {Sat.ElapsedSecs = %r};" % (options, span))
        lines += reports
    return lines


# The state in EarthMJ2000Eq, the axes of GMAT's integration, of Sat.OrbitSTM and of Sat.OrbitErrorCovariance:
# GmatReport turns them to ICRF by the constant rotation R0 between the given state (EarthICRF) and the first report
STATE_REPORT = "Report RF Sat.X Sat.Y Sat.Z Sat.VX Sat.VY Sat.VZ;"
STM_REPORT = "Report RF Sat.OrbitSTM;"
COVARIANCE_REPORT = "Report RF Sat.OrbitErrorCovariance;"


def covariance_lines(case):
    p0 = case["covariance"]["p0_si"]
    lines = ["Create Array P0[6,6];"]
    body = []
    # m^2, m^2/s and m^2/s^2 to km^2, km^2/s and km^2/s^2: every element divided by 1e6
    for i in range(6):
        for j in range(6):
            body.append("P0(%d,%d) = %r;" % (i + 1, j + 1, p0[6 * i + j] / 1.0e6))
    return lines, body + ["Sat.OrbitErrorCovariance = P0;"]


def noise_lines(case, update_step):
    # q_T alone; GMAT rejects a zero sigma, so R and N take 1e-13 km/s^1.5, a density of 1e-26 km^2/s^3 (1e-20 m^2/s^3)
    sigma_t = (case["covariance"]["tangential_noise_m2_s3"] / 1.0e6) ** 0.5
    return [
        "Create CoordinateSystem RTN;",
        "GMAT RTN.Origin = Earth;",
        "GMAT RTN.Axes = ObjectReferenced;",
        "GMAT RTN.XAxis = R;",
        "GMAT RTN.ZAxis = N;",
        "GMAT RTN.Primary = Earth;",
        "GMAT RTN.Secondary = Sat;",
        "Create ProcessNoiseModel SNC;",
        "GMAT SNC.Type = StateNoiseCompensation;",
        "GMAT SNC.CoordinateSystem = RTN;",
        "GMAT SNC.AccelNoiseSigma = [1e-13 %r 1e-13];" % sigma_t,
        "GMAT SNC.UpdateTimeStep = %r;" % update_step,
        "GMAT Sat.ProcessNoiseModel = SNC;",
    ]


def write(directory, variant, lines):
    with open(os.path.join(directory, variant + ".script"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def generate(case, output):
    directory = os.path.join(output, case["name"])
    os.makedirs(directory, exist_ok=True)
    state = case["state_m_m_s"]
    spacecraft = case["spacecraft"]
    coefficients = (spacecraft["drag_coefficient"], spacecraft["reflectivity_coefficient"])

    write(directory, "nominal", header(case, state, coefficients) + report_file(case, "nominal") +
          sequence(case, ", 'STM'", [STATE_REPORT, STM_REPORT]))
    # The same at half the step: the step is settled when Phi at the step and at half of it agree well below what the
    # comparison resolves (decision 7)
    half = dict(case, fixed_step_s=case["fixed_step_s"] / 2.0)
    write(directory, "nominal_half", header(half, state, coefficients) + report_file(case, "nominal_half") +
          sequence(case, ", 'STM'", [STATE_REPORT, STM_REPORT]))

    steps = case["central_differences"]
    for k, component in enumerate(COMPONENTS):
        step = steps["position_step_m"] if k < 3 else steps["velocity_step_m_s"]
        for sign, suffix in ((1.0, "p"), (-1.0, "m")):
            perturbed = list(state)
            perturbed[k] += sign * step
            variant = "cd_%s%s" % (component, suffix)
            write(directory, variant, header(case, perturbed, coefficients) + report_file(case, variant) +
                  sequence(case, "", [STATE_REPORT]))
    for index, (name, key) in enumerate((("cd", "drag_coefficient_step"), ("cr", "reflectivity_coefficient_step"))):
        if steps[key] == 0.0:
            continue
        for sign, suffix in ((1.0, "p"), (-1.0, "m")):
            perturbed = list(coefficients)
            perturbed[index] *= 1.0 + sign * steps[key]
            variant = "cd_%s%s" % (name, suffix)
            write(directory, variant, header(case, state, perturbed) + report_file(case, variant) +
                  sequence(case, "", [STATE_REPORT]))

    if case["drag"]:
        # The density gate of the design of #408 (decision 6): GMAT's density at every output epoch of the nominal
        # trajectory, in kg/km^3, compared by GmatReferenceTests with the density of the library at the same states
        write(directory, "density", header(case, state, coefficients) + report_file(case, "density") +
              sequence(case, "", [STATE_REPORT.replace(";", " Sat.FM.AtmosDensity;")]))

    if "covariance" in case:
        declarations, assignment = covariance_lines(case)
        reports = [STATE_REPORT, STM_REPORT, COVARIANCE_REPORT]
        cov = sequence(case, ", 'STM', 'Covariance'", reports, assignment)
        write(directory, "cov", header(case, state, coefficients) + declarations + report_file(case, "cov") + cov)
        # With the noise, P0 is the small diagonal of cases.json, so that P is almost Q: Q taken as P minus GMAT's
        # own propagated P0 resolves Q far better than the difference of two P of the size of P0 (measured on G1)
        small = case["covariance"]["noise_p0_diagonal_si"]
        noise_assignment = ["P0(%d,%d) = %r;" % (i + 1, j + 1, small[i] / 1.0e6 if i == j else 0.0)
                            for i in range(6) for j in range(6)] + ["Sat.OrbitErrorCovariance = P0;"]
        for step in case["covariance"]["noise_steps_s"]:
            text = repr(float(step))
            variant = "snc_" + (text[:-2] if text.endswith(".0") else text)
            noisy = sequence(case, ", 'STM', 'Covariance'", reports, noise_assignment)
            stepped = dict(case, fixed_step_s=step)
            write(directory, variant, header(stepped, state, coefficients) + declarations + noise_lines(case, step) +
                  report_file(case, variant) + noisy)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    with open(sys.argv[1]) as f:
        cases = json.load(f)["cases"]
    for case in cases:
        generate(case, sys.argv[2])


if __name__ == "__main__":
    main()
